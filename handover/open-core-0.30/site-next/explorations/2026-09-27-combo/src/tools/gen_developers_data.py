#!/usr/bin/env python3
"""Write src/js/developers-data.mjs: the data behind the Developers page's kshana-mcp player.

Source: src/data/mcp-session.json, the real kshana-mcp session recorded by
tools/record_mcp_session.py (the same file Home's player reads through build.py's page data).
Nothing is retyped: the module is that JSON, verbatim, as an ES module default export.

Usage:  python3 src/tools/gen_developers_data.py          write the module
        python3 src/tools/gen_developers_data.py --check  exit 1 when the module is stale

Run it again after the session is re-recorded. When build.py passes the session to the
Developers page as page data (SHARED-REQUESTS-R4.md, Developers), developers.mjs prefers that.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.dirname(HERE)
IN = os.path.join(SRC, "data", "mcp-session.json")
OUT = os.path.join(SRC, "js", "developers-data.mjs")


def render():
    d = json.load(open(IN, encoding="utf-8"))
    body = json.dumps({"mcp": d}, ensure_ascii=False, separators=(",", ":"))
    return ("// GENERATED by src/tools/gen_developers_data.py from src/data/mcp-session.json. Do not edit.\n"
            f"export default {body};\n")


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            print("developers-data.mjs is stale: run python3 src/tools/gen_developers_data.py")
            sys.exit(1)
        print("developers-data.mjs is current")
        sys.exit(0)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, SRC)} ({len(text):,} bytes)")
