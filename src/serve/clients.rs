//! # Generated API clients (roadmap A5a)
//!
//! A Python client (standard library only) and a TypeScript client (`fetch` only), generated
//! from [`super::api::ROUTES`], the table the router and the OpenAPI document are built from,
//! so a route cannot exist without its client method. Method names are the OpenAPI
//! `operationId`s (`get_jobs_id`; `getJobsId` in TypeScript). `kshana-pro clients` writes
//! them; `tests/service_clients.rs` checks that the committed copies are current and drives
//! both against a running server.

use super::api::{Route, RouteId, ROUTES};
use super::openapi::{operation_id, path_params};

/// How a route's response is returned.
fn returns_text(r: &Route) -> bool {
    matches!(
        r.id,
        RouteId::Health | RouteId::Board | RouteId::JobArtefact | RouteId::EloranExample
    )
}

/// The request body: `json`, `text` or none.
fn body_kind(r: &Route) -> Option<&'static str> {
    r.request.map(|(media, _)| {
        if media == "application/json" {
            "json"
        } else {
            "text"
        }
    })
}

fn camel(s: &str) -> String {
    let mut out = String::new();
    let mut up = false;
    for c in s.chars() {
        if c == '_' {
            up = true;
        } else if up {
            out.extend(c.to_uppercase());
            up = false;
        } else {
            out.push(c);
        }
    }
    out
}

fn py_path(r: &Route) -> String {
    let mut p = r.path.to_string();
    for name in path_params(r.path) {
        p = p.replace(&format!("{{{name}}}"), &format!("{{_q({name})}}"));
    }
    if path_params(r.path).is_empty() {
        format!("\"{p}\"")
    } else {
        format!("f\"{p}\"")
    }
}

fn ts_path(r: &Route) -> String {
    let mut p = r.path.to_string();
    for name in path_params(r.path) {
        p = p.replace(
            &format!("{{{name}}}"),
            &format!("${{encodeURIComponent({name})}}"),
        );
    }
    format!("`{p}`")
}

const PY_HEAD: &str = r#"# Kshana Pro service client (Python 3.9+, standard library only).
# GENERATED by `kshana-pro clients` from the service's route table; do not edit by hand.
# PROPRIETARY: part of Kshana Pro. See LICENSE.
"""Client for the Kshana Pro HTTP service (docs/SERVICE.md).

    from kshana_pro_client import KshanaProClient
    c = KshanaProClient("http://127.0.0.1:8088", token=os.environ.get("KSHANA_PRO_KEY"))
    job = c.post_jobs({"op": "run", "request": {"scenario": open("s.toml").read()}})
    status = c.wait_job(job["job_id"])
    result = c.get_jobs_id_result(job["job_id"])
"""
import json
import time
import urllib.error
import urllib.parse
import urllib.request

__all__ = ["KshanaProClient", "KshanaProError"]


class KshanaProError(Exception):
    """A response other than 2xx: `status` and the decoded `body` (a dict when JSON)."""

    def __init__(self, status, body):
        super().__init__(f"HTTP {status}: {body}")
        self.status = status
        self.body = body


def _q(v):
    return urllib.parse.quote(str(v), safe="")


class KshanaProClient:
    def __init__(self, base_url, token=None, timeout=120.0):
        """`token`: an API key or an OIDC bearer token (sent as Authorization: Bearer)."""
        self.base_url = base_url.rstrip("/")
        self.token = token
        self.timeout = timeout

    def _call(self, method, path, query=None, body=None, content_type=None, text=False):
        url = self.base_url + path
        q = {k: v for k, v in (query or {}).items() if v is not None}
        if q:
            url += "?" + urllib.parse.urlencode(q)
        headers = {"Accept": "application/json"}
        data = None
        if body is not None:
            data = body.encode("utf-8")
            headers["Content-Type"] = content_type
        if self.token:
            headers["Authorization"] = "Bearer " + self.token
        req = urllib.request.Request(url, data=data, method=method, headers=headers)
        try:
            with urllib.request.urlopen(req, timeout=self.timeout) as r:
                raw = r.read().decode("utf-8")
        except urllib.error.HTTPError as e:
            raw = e.read().decode("utf-8", "replace")
            try:
                raw = json.loads(raw)
            except ValueError:
                pass
            raise KshanaProError(e.code, raw) from None
        return raw if text else json.loads(raw)

    def wait_job(self, job_id, poll_s=0.5, timeout_s=600.0):
        """Poll a job until it has succeeded or failed; return its status document."""
        end = time.monotonic() + timeout_s
        while True:
            s = self.get_jobs_id(job_id)
            if s["state"] in ("succeeded", "failed"):
                return s
            if time.monotonic() > end:
                raise TimeoutError(f"job {job_id} is still {s['state']}")
            time.sleep(poll_s)
"#;

const TS_HEAD: &str = r#"// Kshana Pro service client (TypeScript; runs on Node 18+, Deno and browsers with fetch).
// GENERATED by `kshana-pro clients` from the service's route table; do not edit by hand.
// PROPRIETARY: part of Kshana Pro. See LICENSE.
//
//   const c = new KshanaProClient("http://127.0.0.1:8088", process.env.KSHANA_PRO_KEY);
//   const job = await c.postJobs({ op: "run", request: { scenario } });
//   await c.waitJob(job.job_id);
//   const result = await c.getJobsIdResult(job.job_id);

export class KshanaProError extends Error {
  status: number;
  body: unknown;
  constructor(status: number, body: unknown) {
    super(`HTTP ${status}: ${typeof body === "string" ? body : JSON.stringify(body)}`);
    this.status = status;
    this.body = body;
  }
}

type Query = Record<string, string | number | undefined>;

export class KshanaProClient {
  baseUrl: string;
  token?: string;
  /** `token`: an API key or an OIDC bearer token (sent as Authorization: Bearer). */
  constructor(baseUrl: string, token?: string) {
    this.baseUrl = baseUrl.replace(/\/+$/, "");
    this.token = token;
  }

  private async call(
    method: string,
    path: string,
    query?: Query,
    body?: string,
    contentType?: string,
    text = false,
  ): Promise<any> {
    let url = this.baseUrl + path;
    const q = Object.entries(query ?? {}).filter(([, v]) => v !== undefined);
    if (q.length) {
      url += "?" + new URLSearchParams(q.map(([k, v]) => [k, String(v)])).toString();
    }
    const headers: Record<string, string> = { Accept: "application/json" };
    if (body !== undefined && contentType) headers["Content-Type"] = contentType;
    if (this.token) headers["Authorization"] = `Bearer ${this.token}`;
    const r = await fetch(url, { method, headers, body });
    const raw = await r.text();
    if (!r.ok) {
      let b: unknown = raw;
      try {
        b = JSON.parse(raw);
      } catch {
        // not JSON: keep the text
      }
      throw new KshanaProError(r.status, b);
    }
    return text ? raw : JSON.parse(raw);
  }

  /** Poll a job until it has succeeded or failed; resolves to its status document. */
  async waitJob(jobId: string, pollMs = 500, timeoutMs = 600_000): Promise<any> {
    const end = Date.now() + timeoutMs;
    for (;;) {
      const s = await this.getJobsId(jobId);
      if (s.state === "succeeded" || s.state === "failed") return s;
      if (Date.now() > end) throw new Error(`job ${jobId} is still ${s.state}`);
      await new Promise((res) => setTimeout(res, pollMs));
    }
  }
"#;

/// The Python client.
pub fn python() -> String {
    let mut s = PY_HEAD.to_string();
    for r in ROUTES {
        let name = operation_id(r.method, r.path);
        let mut args: Vec<String> = path_params(r.path).iter().map(|p| p.to_string()).collect();
        let body = body_kind(r);
        match body {
            Some("json") => args.push("body".into()),
            Some(_) => args.push("text".into()),
            None => {}
        }
        for (q, _) in r.query {
            args.push(format!("{q}=None"));
        }
        let sig = std::iter::once("self".to_string())
            .chain(args)
            .collect::<Vec<_>>()
            .join(", ");
        let query = if r.query.is_empty() {
            "None".to_string()
        } else {
            format!(
                "{{{}}}",
                r.query
                    .iter()
                    .map(|(q, _)| format!("\"{q}\": {q}"))
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        };
        let (b, ct) = match body {
            Some("json") => ("json.dumps(body)", "\"application/json\""),
            Some(_) => ("text", "\"text/plain\""),
            None => ("None", "None"),
        };
        let role = r
            .role
            .map_or("none (no credential)".into(), |x| x.as_str().to_string());
        s.push_str(&format!(
            "\n    def {name}({sig}):\n        \"\"\"{} {}: {}. Role: {role}.\"\"\"\n        return self._call(\"{}\", {}, {query}, {b}, {ct}, text={})\n",
            r.method,
            r.path,
            r.summary.replace('"', "'"),
            r.method,
            py_path(r),
            if returns_text(r) { "True" } else { "False" }
        ));
    }
    s
}

/// The TypeScript client.
pub fn typescript() -> String {
    let mut s = TS_HEAD.to_string();
    for r in ROUTES {
        let name = camel(&operation_id(r.method, r.path));
        let mut args: Vec<String> = path_params(r.path)
            .iter()
            .map(|p| format!("{p}: string"))
            .collect();
        let body = body_kind(r);
        match body {
            Some("json") => args.push("body: unknown".into()),
            Some(_) => args.push("text: string".into()),
            None => {}
        }
        if !r.query.is_empty() {
            args.push(format!(
                "query: {{ {} }} = {{}}",
                r.query
                    .iter()
                    .map(|(q, _)| format!("{q}?: string | number"))
                    .collect::<Vec<_>>()
                    .join("; ")
            ));
        }
        let (b, ct) = match body {
            Some("json") => ("JSON.stringify(body)", "\"application/json\""),
            Some(_) => ("text", "\"text/plain\""),
            None => ("undefined", "undefined"),
        };
        let role = r
            .role
            .map_or("none (no credential)".into(), |x| x.as_str().to_string());
        s.push_str(&format!(
            "\n  /** {} {}: {}. Role: {role}. */\n  {name}({}): Promise<{}> {{\n    return this.call(\"{}\", {}, {}, {b}, {ct}, {});\n  }}\n",
            r.method,
            r.path,
            r.summary,
            args.join(", "),
            if returns_text(r) { "string" } else { "any" },
            r.method,
            ts_path(r),
            if r.query.is_empty() { "undefined" } else { "query" },
            returns_text(r)
        ));
    }
    s.push_str("}\n");
    s
}
