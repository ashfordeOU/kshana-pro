// Writes the Bridge replay's bundled coastline (replay/data/coast.json and coast.manifest.json) from Natural Earth.
//
//   node tools_replay_coast.mjs [--src <ne_10m_land.geojson>]     (without --src it downloads the pinned file)
//
// Natural Earth is public domain (https://www.naturalearthdata.com/about/terms-of-use/), 1:10 million scale land
// polygons, taken at the pinned release tag of nvkelso/natural-earth-vector below and checked against the SHA-256
// below before anything is read. Only land inside a few small windows (one per replay demo) is kept, clipped to the
// window, with coordinates rounded to 0.0001 degree, so the file stays small and the page fetches nothing at run
// time. A coastline at this scale is for orientation only: it is not a chart and not for navigation.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";

const TAG = "v5.1.2";
const URL_ = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${TAG}/geojson/ne_10m_land.geojson`;
const SHA256 = "1ac90796408bc6ad6911d69448485d3c4dbf2190370080368a09976e1c9f7416";
// [lat0, lat1, lon0, lon1] windows around each demo's track (a margin of about 60 km), and the demos that use it.
export const REGIONS = [
  { id: "dover-strait", name: "Dover Strait", box: [50.4, 51.6, 0.6, 2.4], demos: ["coastal-drag-off"] },
  { id: "gulf-of-finland", name: "Gulf of Finland", box: [59.2, 60.5, 24.3, 25.5], demos: ["tallinn-helsinki", "masked-sky"] },
  { id: "hardanger-sogn", name: "Western Norway fjords", box: [60.5, 61.4, 4.9, 7.1], demos: ["fjord-natural-degradation"] },
  { id: "north-sea-east", name: "Southern North Sea, east", box: [53.3, 54.7, 3.0, 5.2], demos: ["combined-event"] },
  { id: "north-sea-central", name: "Central North Sea", box: [54.6, 55.8, 1.6, 3.6], demos: ["open-sea-jamming"] },
  { id: "north-sea-south", name: "Southern North Sea, west", box: [53.0, 54.1, 2.6, 4.2], demos: ["port-approach-time-spoof"] },
];

// Sutherland-Hodgman against the window; a ring is [[lon, lat], ...].
function clipRing(ring, [la0, la1, lo0, lo1]) {
  const edges = [
    [(p) => p[0] >= lo0, (a, b) => [lo0, a[1] + ((b[1] - a[1]) * (lo0 - a[0])) / (b[0] - a[0])]],
    [(p) => p[0] <= lo1, (a, b) => [lo1, a[1] + ((b[1] - a[1]) * (lo1 - a[0])) / (b[0] - a[0])]],
    [(p) => p[1] >= la0, (a, b) => [a[0] + ((b[0] - a[0]) * (la0 - a[1])) / (b[1] - a[1]), la0]],
    [(p) => p[1] <= la1, (a, b) => [a[0] + ((b[0] - a[0]) * (la1 - a[1])) / (b[1] - a[1]), la1]],
  ];
  let pts = ring;
  for (const [inside, cut] of edges) {
    const next = [];
    for (let i = 0; i < pts.length; i++) {
      const a = pts[i], b = pts[(i + 1) % pts.length];
      if (inside(b)) { if (!inside(a)) next.push(cut(a, b)); next.push(b); } else if (inside(a)) next.push(cut(a, b));
    }
    pts = next;
    if (!pts.length) return [];
  }
  return pts;
}
const r4 = (v) => Math.round(v * 1e4) / 1e4;

const arg = (n) => { const i = process.argv.indexOf("--" + n); return i > 0 ? process.argv[i + 1] : null; };
const here = new URL(".", import.meta.url).pathname;
if (import.meta.url === `file://${process.argv[1]}`) {
  const src = arg("src");
  const buf = src ? readFileSync(src) : Buffer.from(await (await fetch(URL_)).arrayBuffer());
  const sha = createHash("sha256").update(buf).digest("hex");
  if (sha !== SHA256) { console.error(`refusing: the land file's SHA-256 is ${sha}, not the pinned ${SHA256}`); process.exit(1); }
  const gj = JSON.parse(buf.toString("utf8"));
  const rings = [];
  for (const f of gj.features) {
    const g = f.geometry;
    for (const poly of g.type === "Polygon" ? [g.coordinates] : g.coordinates) for (const r of poly) rings.push(r);
  }
  const regions = REGIONS.map((reg) => {
    const [la0, la1, lo0, lo1] = reg.box;
    const out = [];
    for (const r of rings) {
      let a0 = Infinity, a1 = -Infinity, o0 = Infinity, o1 = -Infinity;
      for (const [x, y] of r) { if (x < o0) o0 = x; if (x > o1) o1 = x; if (y < a0) a0 = y; if (y > a1) a1 = y; }
      if (o1 < lo0 || o0 > lo1 || a1 < la0 || a0 > la1) continue;
      const c = clipRing(r.slice(0, -1), reg.box).map(([x, y]) => [r4(x), r4(y)]);
      const dedup = c.filter((p, i) => i === 0 || p[0] !== c[i - 1][0] || p[1] !== c[i - 1][1]);
      if (dedup.length >= 3) out.push(dedup);
    }
    return { id: reg.id, name: reg.name, box: reg.box, demos: reg.demos, rings: out };
  });
  const doc = {
    note: "Generated by tools_replay_coast.mjs from Natural Earth 1:10m land (public domain); orientation only, not a chart. Rings are [lon, lat], clipped to each window, drawn with the even-odd rule.",
    regions,
  };
  writeFileSync(join(here, "replay", "data", "coast.json"), JSON.stringify(doc));
  writeFileSync(join(here, "replay", "data", "coast.manifest.json"), JSON.stringify({
    source: "Natural Earth, ne_10m_land", url: URL_, repository: "https://github.com/nvkelso/natural-earth-vector", tag: TAG, sha256: SHA256,
    licence: "Public domain (Natural Earth terms of use: https://www.naturalearthdata.com/about/terms-of-use/); no attribution required, given here as a courtesy",
    scale: "1:10 million", processing: "clipped to the windows below (Sutherland-Hodgman), coordinates rounded to 0.0001 degree, nothing simplified",
    windows: REGIONS.map((r) => ({ id: r.id, name: r.name, box_lat0_lat1_lon0_lon1: r.box, rings: regions.find((x) => x.id === r.id).rings.length })),
  }, null, 1) + "\n");
  console.log(regions.map((r) => `${r.id}: ${r.rings.length} rings, ${r.rings.reduce((a, x) => a + x.length, 0)} points`).join("\n"));
}
