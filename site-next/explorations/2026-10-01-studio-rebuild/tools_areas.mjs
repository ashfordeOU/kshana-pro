// Builds the capability map's data from the files on disk (never typed by hand):
//   data/areas.json            the bundled areas
//   <group>/areas.json         an optional group's area, written into its own folder
// Each area: its scenario count, a small preview read from the first of its recorded runs
// that has a line series, and the verification-matrix rows behind the engine kinds its
// scenarios run (lib/areas.mjs explains the rule). Rerun after re-recording: node tools_areas.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { SCENARIOS, DOMAINS, registerGroup, dirOf } from "./lib/catalog.mjs";
import { plainMeaning, taskWords } from "./lib/meaning.mjs";
import { spellOut } from "./lib/abbr.mjs";
import { kindsOfToml, rowsForKind, evidenceMix, validatedShare, previewOf } from "./lib/areas.mjs";

const here = new URL(".", import.meta.url).pathname;
const readJson = (f) => JSON.parse(readFileSync(here + f, "utf8"));
const matrix = readJson("data/verification-matrix.json");
const rows = matrix.rows;

// The kind -> module table comes from the engine package in ./pkg (0.36 or later), never from a copy kept
// here. An older package lacks kind_modules(); copy web/pkg over ./pkg after building the engine, then rerun.
const engine = await import("./pkg/kshana.js");
await engine.default({ module_or_path: readFileSync(here + "pkg/kshana_bg.wasm") });
if (typeof engine.kind_modules !== "function") {
  console.error("tools_areas: ./pkg has no kind_modules(); it is older than 0.36. Rebuild the engine package and copy it here first.");
  process.exit(1);
}
const kindModules = JSON.parse(engine.kind_modules());

const groups = [];
for (const dir of readJson("groups.json").groups || []) {
  if (!existsSync(here + dir + "index.json")) continue;
  const g = readJson(dir + "index.json");
  registerGroup({ ...g, dir });
  groups.push({ dir, domain: g.domain.id });
}

const recIdx = new Map();
const recordedOf = (file) => {
  const dir = dirOf(file);
  if (!recIdx.has(dir)) recIdx.set(dir, existsSync(here + dir + "recorded/index.json") ? readJson(dir + "recorded/index.json") : { runs: {} });
  const e = recIdx.get(dir).runs[file];
  if (!e || e.error || !e.file) return null;
  try { const rec = readJson(`${dir}recorded/${e.file}`); return { toml: rec.toml, result: JSON.parse(rec.json), engine: recIdx.get(dir).engine_version }; } catch { return null; }
};
const tomlOf = (file) => { const p = here + (dirOf(file) ? dirOf(file) + file : "scenarios/" + file); return existsSync(p) ? readFileSync(p, "utf8") : ""; };

function area(d) {
  const files = SCENARIOS.filter((s) => s[1] === d.id).map((s) => s[0]);
  const kinds = new Set(), idx = [];
  let preview = null, engine = "";
  for (const f of files) {
    const toml = tomlOf(f);
    if (!toml) continue;
    for (const k of kindsOfToml(toml)) { kinds.add(k); idx.push(...rowsForKind(k, rows, kindModules)); }
    if (!preview) {
      const rec = recordedOf(f);
      const p = rec && previewOf(rec.result, rec.toml);
      if (p) { preview = { ...p, file: f }; engine = rec.engine; }
    }
  }
  const mix = evidenceMix(idx, rows);
  const uniq = [...new Set(idx)];
  const examples = (status) => uniq.filter((i) => rows[i].status === status).slice(0, 3).map((i) => rows[i].requirement);
  // No line or map in any run of the area: its first scenario's headline figure, as recorded.
  if (!preview) for (const f of files) {
    const rec = recordedOf(f);
    const m = rec && plainMeaning(rec.result, rec.toml);
    const c = m && m.cards[0];
    if (c) { preview = { type: "figure", title: c.label, value: c.value, unit: c.unit, file: f }; engine = rec.engine; break; }
  }
  return {
    id: d.id, label: d.label, color: d.color, count: files.length, first: files[0] || null,
    kinds: [...kinds], mix, validated_pct: validatedShare(mix) === null ? null : +validatedShare(mix).toFixed(1),
    examples: { validated: examples("VALIDATED"), modelled: examples("MODELLED") },
    preview, engine_version: engine,
  };
}

const core = DOMAINS.filter((d) => !groups.some((g) => g.domain === d.id)).map(area).filter((a) => a.count);
const out = {
  note: "Generated by tools_areas.mjs from lib/catalog.mjs, scenarios/, recorded/ and data/verification-matrix.json. Do not edit by hand.",
  matrix_summary: matrix.summary,
  levels: {
    validated: "Matches an independent external reference: published data, a standard, or third-party code.",
    modelled: "Follows the stated physics and passes internal checks; not yet compared with an outside reference.",
  },
  areas: core,
};
writeFileSync(here + "data/areas.json", JSON.stringify(out) + "\n");
console.log(`data/areas.json: ${core.length} areas, ${core.reduce((n, a) => n + a.count, 0)} scenarios`);
for (const a of core) console.log(`  ${a.id.padEnd(15)} ${String(a.count).padStart(3)} scen  V ${a.mix.validated} M ${a.mix.modelled} P ${a.mix.partner}  preview ${a.preview ? a.preview.file : "none"}`);
// The opening screen's live result: the recorded coverage run, without the engine's own chart
// (the Studio draws the map itself), as compact JSON, so the first screen downloads less.
{
  const HERO = "constellation-multi-gnss-coverage.toml";
  const e = readJson("recorded/index.json").runs[HERO];
  const rec = readJson(`recorded/${e.file}`);
  const hero = { note: "Generated by tools_areas.mjs from recorded/" + e.file + " (the result document unchanged, re-serialised without spaces; the engine's own SVG chart left out). Do not edit by hand.", file: HERO, engine_version: readJson("recorded/index.json").engine_version, toml: rec.toml, summary: rec.summary, json: JSON.stringify(JSON.parse(rec.json)) };
  writeFileSync(here + "data/hero.json", JSON.stringify(hero) + "\n");
  console.log(`data/hero.json: ${(JSON.stringify(hero).length / 1024).toFixed(0)} kB`);
}
// The first paint: the words of every bundled task screen and of the opening screen's result,
// read from the recorded runs with the Studio's own modules (lib/meaning.mjs taskWords), so the
// page can show them before its modules load. The Studio then writes the same words again.
{
  const fp = { note: "Generated by tools_areas.mjs from recorded/ with lib/meaning.mjs; the Studio paints these words before its modules load, then writes the same ones. Do not edit by hand.", engine_version: readJson("recorded/index.json").engine_version, s: {} };
  for (const [file, dom] of SCENARIOS.filter((x) => !dirOf(x[0])).map((x) => [x[0], x[1]])) {
    const rec = recordedOf(file);
    if (!rec || (rec.result && rec.result.error)) continue;
    const d = DOMAINS.find((x) => x.id === dom);
    const e = { title: SCENARIOS.find((x) => x[0] === file)[2], question: SCENARIOS.find((x) => x[0] === file)[3] };
    const w = taskWords(e, d.label, rec.toml, rec.result);
    if (!w.big) continue;
    fp.s[file.replace(/\.toml$/, "")] = { k: w.kicker, c: d.color, t: w.title, u: w.sub, b: w.big, l: w.line, f: w.cards.map((c) => [c.label, c.value, c.unit || "", c.sub || "", c.good ? 1 : 0, c.bad ? 1 : 0]) };
  }
  const hr = recordedOf("constellation-multi-gnss-coverage.toml");
  const m = plainMeaning(hr.result, hr.toml);
  // The map itself (over 100 kB of SVG) waits for the modules; the answer and its figures do not.
  fp.hero = { answer: spellOut(`${m.big} ${m.line}`, new Set()), f: m.cards.map((c) => [c.label, c.value, c.unit || ""]) };
  // The opening screen needs only its own few words: a file of its own, so it arrives at once.
  writeFileSync(here + "data/firstpaint-home.json", JSON.stringify({ note: fp.note, engine_version: fp.engine_version, hero: fp.hero }) + "\n");
  delete fp.hero;
  writeFileSync(here + "data/firstpaint.json", JSON.stringify(fp) + "\n");
  console.log(`data/firstpaint.json: ${Object.keys(fp.s).length} task screens + the opening result, ${(JSON.stringify(fp).length / 1024).toFixed(0)} kB`);
}
for (const g of groups) {
  const d = DOMAINS.find((x) => x.id === g.domain);
  const a = area(d);
  writeFileSync(here + g.dir + "areas.json", JSON.stringify({ note: out.note, areas: [a] }) + "\n");
  console.log(`${g.dir}areas.json: ${a.count} scenarios  V ${a.mix.validated} M ${a.mix.modelled}  preview ${a.preview ? a.preview.file : "none"}`);
}
