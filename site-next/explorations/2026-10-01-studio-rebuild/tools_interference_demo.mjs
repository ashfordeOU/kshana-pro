// Builds interference/demo/ (the interference map page's SYNTHETIC demo), two parts:
//   1. copies the CLI's own synthetic sample outputs (examples/interference-map/output/*.geojson of the
//      public repository), unchanged, so the demo shows exactly what `kshana interference-map` writes;
//   2. writes one extra file the samples do not cover, a CONFOUNDED ADS-B day (adsb-2026-03-02.geojson), with
//      a fixed seed, so the page's day picker and the confounded-day wording can be shown.
// Every number is made up: no tracking source, partner data or real day is involved, and each file's data
// block says so. Format: kshana-interference-map/v1, format_version 1 (docs/INTERFERENCE-MAP.md).
//   node tools_interference_demo.mjs --repo <checkout holding examples/interference-map>
import { writeFileSync, mkdirSync } from "node:fs";
const here = new URL(".", import.meta.url).pathname;
const CELL = 0.5, SCHEMA = "kshana-interference-map/v1";
let seed = 20260301;
const rnd = () => { seed = (seed * 1664525 + 1013904223) >>> 0; return seed / 4294967296; };
const ri = (a, b) => a + Math.floor(rnd() * (b - a + 1));
const r4 = (x) => Math.round(x * 1e4) / 1e4;
const feature = (i, j, props) => {
  const s = -90 + i * CELL, w = -180 + j * CELL, n = s + CELL, e = w + CELL;
  return { type: "Feature", properties: { ...props, cell_i: i, cell_j: j }, geometry: { type: "Polygon", coordinates: [[[w, s], [e, s], [e, n], [w, n], [w, s]]] } };
};
// The same made-up open-ocean region as the CLI's synthetic sample (cell rows 238 to 243, columns 257 to 267).
const rows = [], cols = [];
for (let i = 238; i <= 243; i++) rows.push(i);
for (let j = 257; j <= 267; j++) cols.push(j);
const centre = (i, j) => [-90 + (i + 0.5) * CELL, -180 + (j + 0.5) * CELL];
const dist = (i, j, la, lo) => { const [a, b] = centre(i, j); return Math.hypot(a - la, (b - lo) * 0.5); };
const data = (kind) => ({
  dataset: "custom", name: "SYNTHETIC demonstration fixture (not derived from any tracking source)", licence: "CC0-1.0 (synthetic data)",
  licence_url: "https://creativecommons.org/publicdomain/zero/1.0/",
  attribution: "Synthetic demonstration data generated by Kshana Studio tooling. It describes no real aircraft, vessel, receiver or day.",
  coverage_notes: [`Made-up ${kind === "adsb" ? "aircraft" : "vessel"} counts on a made-up region; coverage here means nothing about any real source.`],
});
const NOTICE = "Aggregate only: no aircraft or vessel identifiers appear in this file. Cells with fewer than the minimum number of distinct aircraft or vessels are omitted. A missing cell was not observed and is not evidence of a clear cell.";

function adsbDay(date, confounded) {
  const raw = [];
  for (const i of rows) for (const j of cols) {
    if (rnd() < 0.22 + (i === rows[0] || i === rows[rows.length - 1] ? 0.2 : 0)) continue; // not observed
    const observed = ri(2, 60);
    if (observed < 5) continue; // suppressed below the publication minimum
    const sampled = observed < 14 ? ri(0, 9) : ri(10, observed);
    const hot = dist(i, j, 30.25, -49.25) < 0.8;
    const bg = confounded ? 0.2 : 0.04;
    const share = sampled ? Math.min(1, Math.max(0, bg + (hot ? 0.5 : 0) + (rnd() - 0.5) * 0.1)) : 0;
    const affected = Math.round(share * sampled);
    raw.push({ i, j, observed, sampled, affected, share: sampled ? affected / sampled : 0 });
  }
  const full = raw.filter((c) => c.sampled >= 10).map((c) => c.share).sort((a, b) => a - b);
  const median = full.length >= 5 ? (full.length % 2 ? full[(full.length - 1) / 2] : (full[full.length / 2 - 1] + full[full.length / 2]) / 2) : null;
  const dayConfounded = median !== null && median >= 0.15;
  const feats = raw.map((c) => {
    let status = "not_degraded";
    const exceeds = c.sampled >= 10 && c.share >= 0.3 && median !== null && c.share >= median + 0.15;
    if (c.sampled < 10) status = "insufficient_sample"; else if (exceeds && dayConfounded) status = "withheld_day_confounded"; else if (exceeds) status = "degraded";
    return feature(c.i, c.j, { aircraft_observed: c.observed, aircraft_sampled: c.sampled, aircraft_affected: c.affected, affected_share: r4(c.share), status, degraded: status === "degraded" });
  });
  return { type: "FeatureCollection", kshana_interference_map: {
    schema: SCHEMA, format_version: 1, source_kind: "adsb", date, grid: { type: "fixed_lat_lon", cell_deg: CELL },
    method: {
      id: "kshana-interference-map/adsb/v1",
      summary: "Share of distinct aircraft whose NIC/NACp reports are low-accuracy within a fixed grid cell, per UTC day.",
      parameters: { min_alt_ft: 5000, low_nacp_max: 6, low_nic_max: 5, good_nacp_min: 8, good_nic_min: 7, min_baseline_good_reports: 5, min_reports_per_aircraft_in_cell: 3, affected_report_share: 0.5, min_aircraft_sampled: 10, degraded_share: 0.3, background_margin: 0.15, day_confound_background: 0.15, min_cells_for_background: 5, publication_min_distinct: 5 },
      guards: ["airborne reports above the altitude floor only", "distinct aircraft are counted, not reports, so one aircraft cannot dominate a cell", "an aircraft counts only if it sent good-accuracy reports elsewhere the same day (excludes equipment that never reports accuracy)", "the cell share must exceed the day's median cell share by a margin", "a day whose median cell share is itself high is marked confounded and no cell is declared degraded", "cells with fewer than the minimum distinct aircraft are not published"],
      input_stats: { rows: 0, used: 0, rejected_malformed: 0, note: "synthetic fixture: no input rows" },
      caveats: ["SYNTHETIC FIXTURE: every number in this file is made up for the Studio demonstration.", "A degraded cell means a high share of aircraft reported low navigation accuracy there that day. It does not identify interference as the cause.", "Other causes include satellite constellation or augmentation outages, space-weather effects, and receiver or transponder faults.", "Cells with no published entry were not observed by enough aircraft, which is not the same as clear."],
    },
    day: { background_evaluated: median !== null, background_share: median === null ? null : r4(median), day_confounded: dayConfounded, cells_published: feats.length, cells_suppressed_below_min_distinct: 0 },
    data: data("adsb"), kshana_version: "synthetic", notice: NOTICE,
  }, features: feats };
}

import { copyFileSync, readdirSync } from "node:fs";
const ri2 = process.argv.indexOf("--repo");
if (ri2 < 0 || !process.argv[ri2 + 1]) { console.error("usage: node tools_interference_demo.mjs --repo <checkout>"); process.exit(2); }
const samples = process.argv[ri2 + 1] + "/examples/interference-map/output/";
mkdirSync(here + "interference/demo", { recursive: true });
for (const f of readdirSync(samples).filter((x) => x.endsWith(".geojson")).sort()) { copyFileSync(samples + f, here + "interference/demo/" + f); console.log("copied", f); }
const doc = adsbDay("2026-03-02", true);
writeFileSync(here + "interference/demo/adsb-2026-03-02.geojson", JSON.stringify(doc));
console.log("adsb-2026-03-02.geojson", doc.features.length, "cells (confounded: " + doc.kshana_interference_map.day.day_confounded + ")");
