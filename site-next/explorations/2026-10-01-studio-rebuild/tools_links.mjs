// Writes the list of deep links into the Studio: every capability view of every bundled
// scenario, as the URL the site's "Open in Kshana Studio" links use
// (index.html?scenario=<name>&tab=<view>). Nothing here is typed by hand: the scenarios come
// from lib/catalog.mjs, the view of each from its recorded result through lib/kinds.mjs, and
// the animation, report and export rows from native/index.json.
// Run: node tools_links.mjs [--out <DEEP-LINKS.md>] [--json <links.json>]
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";
import { SCENARIOS, DOMAINS, NOT_IN_BROWSER, RECORDED_NATIVELY, registerGroup, dirOf, domainOf } from "./lib/catalog.mjs";
import { capabilityView, capabilityTabs, kindOfRun, resultTabs, preferredTab } from "./lib/kinds.mjs";
import * as G from "./lib/stages.mjs";
import { gunzipSync } from "node:zlib";

const here = new URL(".", import.meta.url).pathname;
const args = process.argv.slice(2);
const opt = (n, d) => { const i = args.indexOf(n); return i < 0 ? d : args[i + 1]; };
const OUT = opt("--out", here + "../../scratch/studio-next/DEEP-LINKS.md");
const JSON_OUT = opt("--json", here + "../../scratch/studio-next/links.json");
// A recording may be gzip (recorded/<name>.json.gz, tools_record.mjs); other files are plain.
const read = (f) => { const b = readFileSync(here + f); return JSON.parse((b[0] === 0x1f && b[1] === 0x8b ? gunzipSync(b) : b).toString("utf8")); };

const nat = { "": read("native/index.json") };
const rec = { "": read("recorded/index.json") };
for (const dir of existsSync(here + "groups.json") ? read("groups.json").groups : []) {
  if (!existsSync(here + dir + "index.json")) continue;
  registerGroup({ ...read(dir + "index.json"), dir });
  nat[dir] = read(dir + "native/index.json"); rec[dir] = read(dir + "recorded/index.json");
}

const link = (name, tab, extra = "") => `index.html?scenario=${name}&tab=${tab}${extra}`;
const rows = [];
for (const [file, domain, title] of SCENARIOS) {
  const dir = dirOf(file), name = file.replace(/\.toml$/, "");
  const entry = rec[dir].runs[file];
  if (!entry || entry.error) continue;
  const r = JSON.parse(read(`${dir}recorded/${entry.file}`).json);
  const toml = read(`${dir}recorded/${entry.file}`).toml;
  const cap = capabilityView(r, toml);
  const n = nat[dir].runs[file] || {};
  const row = { file, name, title, domain: domainOf(domain).label, group: dir ? "optional" : "bundled", kind: kindOfRun(r, toml) || (toml.match(/^\s*kind\s*=\s*"([^"]+)"/m) || [])[1] || "clock", runs: NOT_IN_BROWSER[file] ? (RECORDED_NATIVELY.includes(file) ? "recorded (native engine)" : "command line only") : "browser", links: {} };
  if (cap) {
    row.capability = cap.label; row.tab = cap.tab; row.stage = cap.stage || "";
    row.links.view = link(name, cap.tab);
    if (cap.stage === "spectrum") { row.links.replay = link(name, cap.tab, "&play=1"); row.frames = G.waterfallFrames(r).map((f) => ({ id: f.id, name: f.name, link: link(name, cap.tab, `&frame=${f.id}`) })); }
    if (cap.stage === "timeline") row.links.replay = link(name, cap.tab, "&play=1");
    if (cap.stage === "coverage") { row.links.replay = link(name, cap.tab, "&play=1"); row.fields = G.coverageFields(r).map((f) => ({ key: f.key, label: f.label, link: link(name, cap.tab, `&field=${f.key}`) })); }
    if (cap.stage === "solar") row.views = G.orreryViews(r).map((v) => ({ id: v.id, label: v.label, link: link(name, cap.tab, `&view=${encodeURIComponent(v.id)}`) }));
  }
  // Every view the run has (the Studio's own rule), the view it opens on, and the link a site
  // visual of this run should use: its replay where it has one, else its most telling view.
  row.dir = dir;
  row.tabs = resultTabs(r, toml, { svg: read(`${dir}recorded/${entry.file}`).svg || "", native: n });
  row.preferred = preferredTab(r, toml);
  row.links.best = row.links.replay || link(name, row.preferred);
  if (n.animation) row.links.animation = link(name, "animation");
  if (n.report) row.links.report = link(name, "report");
  row.links.exports = link(name, "exports");
  row.exports = n.exports || [];
  rows.push(row);
}

const capRows = rows.filter((r) => r.capability);
const tabs = capabilityTabs();
let md = `# Kshana Studio: deep links\n\n`;
md += `Generated by \`tools_links.mjs\` in the Studio staging copy (\`explorations/2026-09-30-studio-next/\`) from the scenario catalogue, the recorded results and the native engine's recordings. Do not edit by hand: run \`node tools_links.mjs\` again.\n\n`;
md += `## The pattern\n\n`;
md += `\`<studio>/index.html?scenario=<file without .toml>&tab=<view>\`, where \`<studio>\` is \`playground/\` on the site (the path the site's "Open in Kshana Studio" links already use). The scenario loads, runs in the browser and opens on the named view. Add \`&embed=1\` for the chrome-free embed.\n\n`;
md += `Optional extras:\n\n- \`&play=1\` starts the replay of a waterfall, a mission timeline or a coverage map (not under reduced motion).\n- \`&frame=<id>\` picks the waterfall of a spectrum run (\`band\` or \`panel-0\`, \`panel-1\`, ...).\n- \`&field=<key>\` picks the mapped field of a coverage map.\n- \`&view=<id>\` picks the solar-system drawing (\`planets\`, \`inner\`, \`moons:<Body>\`).\n\n`;
md += `Views (\`tab=\`): ${tabs.map((t) => `\`${t.tab}\` (${t.label})`).join(", ")}, plus \`animation\`, \`report\` and \`exports\` for every scenario that has them, and the older views \`overview\`, \`timeseries\`, \`signal\`, \`holdover\`, \`masks\`, \`stability\`, \`orbit\`, \`ground\`, \`sweep\`, \`json\`.\n\n`;
md += `## Links the site asked for\n\n| Site visual | Link |\n|---|---|\n`;
const want = [
  ["Home `#lband` L-band waterfall", "l-band-waterfall-jamming", "replay"],
  ["Home `#timeline` mission timeline; Missions chained run", "campaign-jam-spoof-holdover-integrity", "replay"],
  ["Home `#lband` campaign the waterfall drives", "campaign-spectrum-holdover-integrity", "view"],
  ["Capabilities `#bands` multi-band spectrum", "multi-band-jamming-waterfall", "view"],
  ["Capabilities `#journey` whole solar system", "solar-system-tour", "view"],
  ["Capabilities `#customise` constellation designer", "constellation-multi-gnss-coverage", "view"],
  ["Capabilities / Missions: LEO mega-constellation", "leo-pnt-mega-shell", "view"],
  ["Capabilities / Missions: lunar relay constellation", "lunar-relay-constellation", "view"],
  ["Capabilities / Missions: Mars orbiter", "mars-orbit-pnt", "view"],
  ["Capabilities / Missions: Europa lander", "europa-surface-pnt", "view"],
  ["Missions: sweep campaign", "campaign-sweep-jammer-power", "view"],
  ["Missions: Monte Carlo campaign", "campaign-monte-carlo-clock-holdover", "view"],
  ["Missions: one jammer, two platforms", "campaign-shared-jammer-sea-road", "view"],
  ["Lunar sector: laser-ranging datum (recorded natively)", "lunar-llr-datum", "view"],
  ["Animation button (any chart)", "campaign-jam-spoof-holdover-integrity", "animation"],
  ["Engine report (any chart)", "l-band-waterfall-jamming", "report"],
  ["Download SigMF / interoperability exports", "l-band-waterfall-jamming", "exports"],
];
for (const [what, name, key] of want) { const r = rows.find((x) => x.name === name); if (r && r.links[key]) md += `| ${what} | \`${r.links[key]}\` |\n`; }
md += `\n## Every capability view\n\n`;
for (const t of tabs) {
  const list = capRows.filter((r) => r.tab === t.tab);
  if (!list.length) continue;
  md += `### ${t.label} (\`tab=${t.tab}\`)\n\n| Scenario | Kind | Runs | Link | Replay | Animation | Report |\n|---|---|---|---|---|---|---|\n`;
  for (const r of list) md += `| ${r.title}${r.group === "optional" ? " (optional preset)" : ""} | \`${r.kind}\` | ${r.runs} | \`${r.links.view}\` | ${r.links.replay ? `\`${r.links.replay}\`` : "—"} | ${r.links.animation ? `\`${r.links.animation}\`` : "—"} | ${r.links.report ? `\`${r.links.report}\`` : "—"} |\n`;
  md += `\n`;
  for (const r of list) {
    if (r.frames && r.frames.length > 1) md += `- ${r.title}, waterfalls: ${r.frames.map((f) => `${f.name} \`${f.link}\``).join("; ")}\n`;
    if (r.views) md += `- ${r.title}, drawings: ${r.views.map((v) => `${v.label} \`${v.link}\``).join("; ")}\n`;
    if (r.fields) md += `- ${r.title}, mapped fields: ${r.fields.map((f) => `${f.label} \`${f.link}\``).join("; ")}\n`;
  }
  md += `\n`;
}
md += `## Animation, engine report and interoperability exports, every scenario\n\nThese three views show files the native command-line engine wrote (the browser build has no writer for them), labelled as recorded in the Studio.\n\n| Scenario | Animation | Report | Exports | Export formats recorded |\n|---|---|---|---|---|\n`;
for (const r of rows) md += `| \`${r.name}\`${r.group === "optional" ? " (optional preset)" : ""} | ${r.links.animation ? `\`${r.links.animation}\`` : "no time axis"} | ${r.links.report ? `\`${r.links.report}\`` : "—"} | \`${r.links.exports}\` | ${r.exports.length ? r.exports.join(", ") : "none apply"} |\n`;
md += `\nCounts: ${rows.length} scenarios with a recorded run (${rows.filter((r) => r.group === "optional").length} in the optional preset folder), ${capRows.length} with a capability view, ${rows.filter((r) => r.links.animation).length} with an animation, ${rows.filter((r) => r.links.report).length} with an engine report, ${rows.filter((r) => r.exports.length).length} with at least one interoperability export.\n`;
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, md);
writeFileSync(JSON_OUT, JSON.stringify(rows, null, 1));
console.log(`${rows.length} scenarios, ${capRows.length} capability views -> ${OUT}`);
