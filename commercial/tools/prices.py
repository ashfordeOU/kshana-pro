#!/usr/bin/env python3
# PROPRIETARY — Kshana Pro overlay. Internal commercial tooling. Not part of the open-source engine.
"""Build the Kshana editions page (roadmap S4) and the private sales price sheet (C9).

Both come from ``commercial/prices.toml`` (the §1c prices the owner approved at gate K4)
and nothing else:

* ``editions`` writes the public editions page. While ``[switch] public_prices`` is false
  (the owner's decision until the public page is approved) it carries **no price at all**:
  every paid line says "Contact us". With the switch on it shows the public prices, and
  Kshana Sovereign still says "Contact us" (owner rule).
* ``sheet`` writes the private sales sheet with every price. It is marked
  ``kshana-private-price-sheet`` and refuses to be written into a public tree
  (``site-next/``, ``docs/``, ``web/``, ``commercial/editions/`` or any ``public``/``site``
  folder).
* ``scan-public DIR...`` fails when a public tree carries the sheet's marker, the Sovereign
  price, or (switch off) any price at all.
* ``build [--check]`` writes (or checks) the committed outputs:
  ``commercial/editions/editions.html`` and ``commercial/sales/PRICE-SHEET.md``.

Standard library only; Python 3.11 or later. Exit codes: 0 ok; 1 check failed; 2 bad input.
"""

from __future__ import annotations

import argparse
import html
import os
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PRICES = ROOT / "commercial" / "prices.toml"
EDITIONS_OUT = ROOT / "commercial" / "editions" / "editions.html"
SHEET_OUT = ROOT / "commercial" / "sales" / "PRICE-SHEET.md"
SHEET_MARKER = "kshana-private-price-sheet"
PUBLIC_DIRS = ("site-next", "docs", "web", "commercial/editions")
PUBLIC_NAMES = {"public", "site", "www", "dist"}
CONTACT = "Contact us"
TEXT_EXT = {".html", ".htm", ".md", ".mdx", ".txt", ".json", ".js", ".ts", ".tsx", ".jsx",
            ".astro", ".vue", ".svelte", ".yml", ".yaml", ".toml", ".xml", ".csv", ".njk"}


class Bad(Exception):
    pass


def load(path: Path = PRICES) -> dict:
    try:
        with open(path, "rb") as f:
            p = tomllib.load(f)
    except (OSError, tomllib.TOMLDecodeError) as e:
        raise Bad(f"{path}: {e}")
    if p.get("format") != "kshana-price-list/1":
        raise Bad("prices.toml: format must be kshana-price-list/1")
    seen = set()
    for kind in ("edition", "product"):
        for it in p.get(kind, []):
            for k in ("id", "name", "price"):
                if not str(it.get(k, "")).strip():
                    raise Bad(f"prices.toml: a {kind} has no {k}")
            if it["id"] in seen:
                raise Bad(f"prices.toml: id {it['id']} twice")
            seen.add(it["id"])
            if "PLACEHOLDER" in it["price"]:
                raise Bad(f"prices.toml: {it['id']} still has a placeholder price")
    sov = [e for e in p.get("edition", []) if e["id"] == "sovereign"]
    if not sov or sov[0].get("public", True):
        raise Bad("prices.toml: Kshana Sovereign must be listed with public = false")
    return p


def public_price(it: dict, switch_on: bool) -> str:
    if it["price"] == "Free":
        return "Free"
    if not switch_on or not it.get("public", False):
        return CONTACT
    return it["price"]


def editions_html(p: dict) -> str:
    on = bool(p.get("switch", {}).get("public_prices", False))
    e = html.escape
    rows = []
    for ed in p.get("edition", []):
        inc = "".join(f"<li>{e(x)}</li>" for x in ed.get("includes", []))
        rows.append(
            f'<tr><th scope="row">{e(ed["name"])}</th><td>{e(ed.get("audience", ""))}</td>'
            f"<td><ul>{inc}</ul></td><td>{e(public_price(ed, on))}</td></tr>"
        )
    prods = "".join(
        f'<tr><th scope="row">{e(pr["name"])}</th><td>{e(pr.get("model", ""))}</td>'
        f"<td>{e(public_price(pr, on))}</td></tr>"
        for pr in p.get("product", [])
    )
    note = ("Prices are published on request while the price list is being finalised. "
            "Contact us for a quote." if not on else
            "Prices in USD, excluding VAT. Kshana Sovereign is quoted per site.")
    return f"""<!doctype html>
<!-- Generated by commercial/tools/prices.py from commercial/prices.toml. Do not edit by hand. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Kshana editions</title>
<style>
body{{font-family:system-ui,sans-serif;margin:0 auto;max-width:960px;padding:24px 16px;line-height:1.5}}
table{{border-collapse:collapse;width:100%;margin:16px 0}}
th,td{{border-bottom:1px solid #ccc;padding:8px;text-align:left;vertical-align:top}}
ul{{margin:0;padding-left:18px}}
</style>
</head>
<body>
<h1>Kshana editions</h1>
<p>Detection, file formats and verification are always free. A paid edition adds the analysis,
the signed evidence products, the fleet and the operations.</p>
<table>
<thead><tr><th>Edition</th><th>For</th><th>Includes</th><th>Price</th></tr></thead>
<tbody>
{chr(10).join(rows)}
</tbody>
</table>
<h2>Evidence packs and services</h2>
<table>
<thead><tr><th>Product</th><th>How it is sold</th><th>Price</th></tr></thead>
<tbody>
{prods}
</tbody>
</table>
<p>{e(note)}</p>
</body>
</html>
"""


def sheet_md(p: dict) -> str:
    lines = [
        f"<!-- {SHEET_MARKER}: PRIVATE, for sales conversations only. Never publish, never attach to a public page. -->",
        "<!-- Generated by commercial/tools/prices.py from commercial/prices.toml. Do not edit by hand. -->",
        "",
        "# Kshana price sheet (private, sales only)",
        "",
        f"Approved {p.get('approved', '?')} by {p.get('approved_by', '?')}. Prices in "
        f"{p.get('currency', 'USD')}, {p.get('vat', 'excluding VAT')}. The public editions page "
        f"shows {'public prices' if p.get('switch', {}).get('public_prices') else 'no prices'} "
        "(switch in commercial/prices.toml); Kshana Sovereign is \"Contact us\" in public.",
        "",
        "## Editions",
        "",
        "| Edition | Model | Price | In public |",
        "|---|---|---|---|",
    ]
    for ed in p.get("edition", []):
        lines.append(f"| {ed['name']} | {ed.get('model', '')} | {ed['price']} | "
                     f"{'listed' if ed.get('public') else CONTACT} |")
    lines += ["", "## Evidence packs and services", "", "| Product | Model | Price |", "|---|---|---|"]
    for pr in p.get("product", []):
        lines.append(f"| {pr['name']} | {pr.get('model', '')} | {pr['price']} |")
    notes = p.get("sales", {}).get("notes", [])
    if notes:
        lines += ["", "## Notes for sales", ""] + [f"- {n}" for n in notes]
    return "\n".join(lines) + "\n"


def is_public_path(out: Path) -> bool:
    try:
        rel = out.resolve().relative_to(ROOT)
        rp = rel.as_posix()
        if any(rp == d or rp.startswith(d + "/") for d in PUBLIC_DIRS):
            return True
    except ValueError:
        pass
    return any(part.lower() in PUBLIC_NAMES for part in out.resolve().parts)


def scan_public(p: dict, dirs: list[str]) -> list[str]:
    on = bool(p.get("switch", {}).get("public_prices", False))
    banned = [SHEET_MARKER]
    for it in p.get("edition", []) + p.get("product", []):
        if it["price"] == "Free":
            continue
        if not on or not it.get("public", False):
            banned.append(it["price"])
    found = []
    for d in dirs:
        for base, subdirs, names in os.walk(d):
            subdirs[:] = [s for s in subdirs if not s.startswith(".") and s not in ("node_modules", "target")]
            for n in names:
                fp = Path(base) / n
                if fp.suffix.lower() not in TEXT_EXT:
                    continue
                try:
                    t = fp.read_text(encoding="utf-8")
                except (UnicodeDecodeError, OSError):
                    continue
                for b in banned:
                    if b in t:
                        what = "the private sheet marker" if b == SHEET_MARKER else "a price that is not public"
                        found.append(f"{fp}: {what}")
                        break
    return found


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--prices", default=str(PRICES))
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("editions")
    s.add_argument("--out", required=True)
    s = sub.add_parser("sheet")
    s.add_argument("--out", required=True)
    s = sub.add_parser("scan-public")
    s.add_argument("dirs", nargs="+")
    s = sub.add_parser("build")
    s.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    try:
        p = load(Path(a.prices))
    except Bad as e:
        print(f"prices: {e}", file=sys.stderr)
        return 2
    if a.cmd == "editions":
        write(Path(a.out), editions_html(p))
        print(f"wrote {a.out}")
    elif a.cmd == "sheet":
        if is_public_path(Path(a.out)):
            print(f"prices: refusing to write the private price sheet into a public tree ({a.out})", file=sys.stderr)
            return 2
        write(Path(a.out), sheet_md(p))
        print(f"wrote {a.out}")
    elif a.cmd == "scan-public":
        found = scan_public(p, a.dirs)
        for f in found:
            print(f)
        if found:
            print(f"prices: FAIL ({len(found)} file(s))", file=sys.stderr)
            return 1
        print("prices: public trees carry no private price", file=sys.stderr)
    elif a.cmd == "build":
        want = {EDITIONS_OUT: editions_html(p), SHEET_OUT: sheet_md(p)}
        stale = [str(k.relative_to(ROOT)) for k, v in want.items()
                 if not k.exists() or k.read_text(encoding="utf-8") != v]
        if a.check:
            if stale:
                print("prices: stale, run commercial/tools/prices.py build: " + ", ".join(stale), file=sys.stderr)
                return 1
            print("prices: committed editions page and price sheet are current", file=sys.stderr)
        else:
            for k, v in want.items():
                write(k, v)
            print("wrote " + ", ".join(str(k.relative_to(ROOT)) for k in want))
    return 0


if __name__ == "__main__":
    sys.exit(main())
